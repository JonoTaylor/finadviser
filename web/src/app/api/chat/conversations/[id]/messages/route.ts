import { NextRequest, NextResponse } from 'next/server';
import { conversationRepo } from '@/lib/repos';
import { z } from 'zod';

const idSchema = z.coerce.number().int().positive().max(2147483647);
// This legacy endpoint never accepts specialist evidence from a browser.
const bodySchema = z.object({
  role: z.enum(['user', 'assistant', 'system']), content: z.string().trim().min(1).max(100_000),
}).strict();
const json = (body: unknown, status = 200) => NextResponse.json(body, { status, headers: { 'Cache-Control': 'private, no-store' } });

export async function POST(
  request: NextRequest,
  { params }: { params: Promise<{ id: string }> },
) {
  try {
    const { id } = await params;
    const parsedId = idSchema.safeParse(id);
    const body = bodySchema.safeParse(await request.json().catch(() => null));
    if (!parsedId.success || !body.success) return json({ error: 'Supply a valid conversation ID, role and message. Specialist evidence is generated by the server.' }, 400);
    if (!await conversationRepo.getConversationById(parsedId.data)) return json({ error: 'Conversation not found.' }, 404);
    const message = await conversationRepo.addMessage(parsedId.data, body.data.role, body.data.content);
    return json(message, 201);
  } catch {
    return json({ error: 'The message save could not be confirmed.' }, 503);
  }
}
